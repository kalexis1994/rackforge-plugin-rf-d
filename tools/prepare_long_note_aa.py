"""Frozen windowed-sinc coefficients and a rate-only derivation of J7 readout."""
import numpy as np
from prepare_dual_chain import ROOT
def taps(fs):
    n=2*(fs//1000)+1;m=np.arange(n,dtype=float)-(n-1)//2
    h=2*22000/fs*np.sinc(2*22000/fs*m)*np.kaiser(n,10.06126)
    return h/h.sum()
def images():
    old=(ROOT/'crates/rf-d-circuit/src/j7_audio_readout.rs').read_text(encoding='utf8').split('#[cfg(test)]')[0]
    old=old.replace('//! Passive offline J7 voltage readout; see J7_READOUT_PROTOCOLO.md.','//! Passive 384 kHz nominal readout; see LONG_NOTE_AA_PROTOCOLO.md.').replace('pub const RATE:u64=48_000;','pub const RATE:u64=384_000;')
    coeff='//! Windowed sinc; generated by prepare_long_note_aa.py, beta 10.06126.\n'
    for fs in [192000,384000]:
        h=taps(fs);coeff+=f'pub const H{fs}:[f64;{len(h)}]=[\n'+''.join(f'    {v:.17e},\n' for v in h)+'];\n'
    return {'crates/rf-d-circuit/src/j7_oversampled_readout.rs':old,'crates/rf-d-circuit/src/j7_antialias_coefficients.rs':coeff,'tools/long_note_aa_probe.rs':probe_image()}
def probe_image():
    s=(ROOT/'tools/j7_readout_probe.rs').read_text(encoding='utf8')
    s=s.replace('src/j7_audio_readout.rs','src/j7_oversampled_readout.rs').replace('use readout::startup;','use readout::startup;\n#[path="../crates/rf-d-circuit/src/j7_antialias.rs"]mod antialias;')
    s=s.replace('[32*US,8*US,4*US,2*US,US]','[2*US,US]').replace('Buffer::<4801>','Buffer::<115585>')
    s=s.replace('while ticks<100000*US','while ticks<301000*US')
    s=s.replace('else if ticks<75000*US{75000*US}else{100000*US}','else if ticks<200000*US{200000*US}else if ticks<300000*US{300000*US}else{301000*US}')
    s=s.replace('(1000*US..75000*US)','(1000*US..200000*US)')
    s=s.replace('let before=audio.clone();','let before=if steps%50000==0{Some(audio.clone())}else{None};')
    s=s.replace('steps%1500==0','steps%50000==0').replace('before.samples()','before.as_ref().unwrap().samples()').replace('before.through_ticks()','before.as_ref().unwrap().through_ticks()').replace('let mut retry=before;retry.append','let mut retry=before.unwrap();retry.append')
    s=s.replace('||old_ticks==75000*US||ticks==100000*US','||ticks==200000*US||old_ticks==200000*US||ticks==300000*US||ticks==301000*US')
    s=s.replace('if ticks==1000*US||ticks==75000*US{assert_eq!', 'if ticks==1000*US||ticks==200000*US{assert_eq!')
    s=s.replace('(ticks/(1000*US)*48)','(ticks/(1000*US)*384)')
    s=s.replace('proposal=if q.error', 'if ticks==75000*US{write!(out,"SEAM,{ticks}").unwrap();state(&mut out,s);writeln!(out).unwrap();}\n        if ticks%(25000*US)==0{writeln!(out,"PROGRESS,{ticks},{steps},{elapsed:0.9e}").unwrap();out.flush().unwrap();}\n        proposal=if q.error')
    a=s.index('assert_eq!(heap,0);assert_eq!(audio.samples().len(),4801)');b=s.index('    writeln!(out,"READOUT,',a)
    s=s[:a]+'''assert_eq!(heap,0);assert_eq!(audio.samples().len(),115585);assert_eq!(audio.samples()[115584].to_bits(),(s.high[115]+s.low[115]).to_bits());
    let mut half=[0.;57793];for (a,b) in half.iter_mut().zip(audio.samples().iter().step_by(2)){*a=*b;}
    let mut aa4=[0.;14401];let mut aa8=[0.;14401];let n=ALLOCS.load(Ordering::Relaxed);
    antialias::convert(&half,&mut aa4,4).unwrap();antialias::convert(audio.samples(),&mut aa8,8).unwrap();assert_eq!(n,ALLOCS.load(Ordering::Relaxed));
    for (i,v) in audio.samples().iter().enumerate(){writeln!(out,"RAW,{i},{v:0.17e}").unwrap();}
    for (i,v) in aa4.iter().enumerate(){writeln!(out,"AA4,{i},{v:0.17e}").unwrap();}
    for (i,v) in aa8.iter().enumerate(){writeln!(out,"AA8,{i},{v:0.17e}").unwrap();}
''' +s[b:]
    return s
def main():
    for n,s in images().items():
        p=ROOT/n
        if p.exists():assert p.read_bytes()==s.encode(),n
        else:p.write_text(s,encoding='utf8',newline='\n')
if __name__=='__main__':main()
