"""Compact the original settled circuit cycle, retaining its reset edge."""
import base64,json,traceback
import numpy as np
from prepare_dual_chain import ROOT,sha,write
from vco1_radau_joined_trace import blocks

def derive():
    listen=json.loads((ROOT/'evidence/voice_vco1_radau_listening01.json').read_text(encoding='utf8'));a,b=listen['window_s']
    entries=[dict(path=ROOT/e['path'],skip_rows=e['skip_rows'],take_rows=e['take_rows']) for e in listen['source_segments']]
    arrays=[]
    for block in blocks(entries):
        t=block[:,0]*125e-9/65536;ids=np.flatnonzero((t>=a)&(t<=b))
        if len(ids):
            lo=max(0,ids[0]-1);hi=min(len(t),ids[-1]+2)
            arrays.append(np.column_stack([t[lo:hi],block[lo:hi,54]+block[lo:hi,188],block[lo:hi,60]+block[lo:hi,194]]))
    raw=np.concatenate(arrays);assert np.all(np.diff(raw[:,0])>0) and raw[0,0]<=a and raw[-1,0]>=b
    t=np.r_[a,raw[(raw[:,0]>a)&(raw[:,0]<b),0],b];p=(t-a)/(b-a);p[0]=0.;p[-1]=1.
    wave=np.column_stack([np.interp(t,raw[:,0],raw[:,k]) for k in [1,2]])
    closure=float(max(abs(wave[0]-wave[-1])));assert closure<=100e-6,closure
    target=wave.copy();target[0]=target[-1]=(wave[0]+wave[-1])/2
    keep={0,len(p)-1};pending=[(0,len(p)-1)]
    while pending:
        lo,hi=pending.pop()
        if hi-lo<=1:continue
        interpolated=target[lo]+((p[lo+1:hi]-p[lo])/(p[hi]-p[lo]))[:,None]*(target[hi]-target[lo])
        err=np.max(abs(target[lo+1:hi]-interpolated),axis=1);k=int(np.argmax(err))+lo+1
        if max(err)>50e-6:keep.add(k);pending.extend([(lo,k),(k,hi)])
    ids=sorted(keep);table=np.column_stack([p[ids],target[ids]])
    error=float(np.max(abs(wave-np.column_stack([np.interp(p,table[:,0],table[:,k]) for k in [1,2]]))))
    assert error<=50e-6,error
    source='crates/rf-d-circuit/src/hybrid_phase_profile.rs';path=ROOT/source;assert not path.exists()
    text='//! Original settled circuit DRIVE48/TRI54; 50 uV piecewise-linear compaction.\n//! Generated by prepare_hybrid_profile.py; reset edge retained, no bandlimit.\n'
    text+=f'pub const KNOTS:[[f64;3];{len(table)}]=[\n'+''.join('    ['+','.join(f'{v:.17e}' for v in row)+'],\n' for row in table)+'];\n'
    path.write_text(text,encoding='utf8',newline='\n')
    return dict(passed=True,cycle_window_s=[a,b],raw_knots=len(p),compacted_knots=len(table),maximum_source_error_v=error,closure_difference_v=closure,error_gate_v=50e-6,closure_gate_v=100e-6,table=table.tolist(),generated_source=source,generated_source_sha256=sha(path),private_used_sha256={e['path']:sha(ROOT/e['path']) for e in listen['source_segments']},source_sha256={n:sha(ROOT/n) for n in ['tools/prepare_hybrid_profile.py','tools/vco1_radau_joined_trace.py','tools/vco1_radau_trace.py','evidence/voice_vco1_radau_listening01.json','docs/HYBRID_VOZ_PROTOCOLO.md']},new_private_sound_inputs=0)
def main():
    out=ROOT/'evidence/hybrid_voice_profile01.json';assert not out.exists()
    try:r=derive()
    except Exception:
        r=dict(passed=False,failure=traceback.format_exc(),source_base64=base64.b64encode((ROOT/'tools/prepare_hybrid_profile.py').read_bytes()).decode())
        try:derive();r['unchanged_replay']='unexpected pass'
        except Exception:r['unchanged_replay']=traceback.format_exc()
    write(out,r);print('HYBRID_CYCLE',r['passed'],r.get('compacted_knots'),r.get('maximum_source_error_v'),r.get('failure',''),flush=True)
    if not r['passed']:raise SystemExit(1)
if __name__=='__main__':main()
